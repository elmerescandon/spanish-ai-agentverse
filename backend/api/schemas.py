"""Pydantic schemas and enums for the backend HTTP API."""

from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, Field


class ProtocolStatus(StrEnum):
    """Lifecycle status of a clinical protocol."""

    UPLOADED = "uploaded"
    ANALYZING = "analyzing"
    READY = "ready"


class PipelineStep(StrEnum):
    """Pipeline analysis step producing recommendations."""

    COMPLETENESS = "completeness"
    COMPARISON = "comparison"
    COHORT = "cohort"


class Severity(StrEnum):
    """Severity level of an identified protocol gap."""

    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"


class RecommendationStatus(StrEnum):
    """Review decision status for a recommendation."""

    PENDING = "pending"
    ACCEPTED = "accepted"
    REJECTED = "rejected"


class HealthResponse(BaseModel):
    """Response returned by the health check endpoint."""

    status: Literal["ok"] = "ok"


class ProtocolCreateRequest(BaseModel):
    """Payload to create a new protocol for gap analysis."""

    title: str = Field(min_length=1)
    data: dict[str, object] = Field(default_factory=dict)


class ProtocolSummary(BaseModel):
    """Summary representation of a registered protocol."""

    protocol_id: str
    title: str
    status: ProtocolStatus
    data: dict[str, object] = Field(default_factory=dict)


class Recommendation(BaseModel):
    """Gap recommendation generated by an agent pipeline step."""

    recommendation_id: str
    protocol_id: str
    source_step: PipelineStep
    severity: Severity
    title: str
    description: str
    status: RecommendationStatus = RecommendationStatus.PENDING
    comment: str | None = None
    details: dict[str, object] = Field(default_factory=dict)


class RecommendationDecisionRequest(BaseModel):
    """Reviewer decision payload for a recommendation."""

    status: RecommendationStatus
    comment: str | None = None


# --- Demo pipeline contract -------------------------------------------------
# One endpoint per /demo section: upload fills "ingest", then the three
# recommendation endpoints run in parallel and each fills its own step.
# Mirrors frontend/src/lib/demo/types.ts.


class StepId(StrEnum):
    """Section of the /demo page a response fills."""

    INGEST = "ingest"
    CHECK = "check"
    PEERS = "peers"
    COHORT = "cohort"


class EvidenceSource(StrEnum):
    """Where a piece of evidence was taken from."""

    PROTOCOL = "protocol"
    CONSENT = "consent"
    AACT = "aact"
    MIMIC = "mimic"
    NHANES = "nhanes"


class TraceKind(StrEnum):
    """Kind of reasoning step in an agent's trace."""

    RETRIEVE = "retrieve"
    RULE = "rule"
    COMPARE = "compare"
    CONCLUDE = "conclude"


class MetricTone(StrEnum):
    """Colour cue for a metric on the /demo page."""

    NEUTRAL = "neutral"
    GOOD = "good"
    WARN = "warn"
    RISK = "risk"


class Evidence(BaseModel):
    """Verbatim quote backing a decision."""

    evidence_id: str
    source: EvidenceSource
    document: str
    page: int | None = None
    quote: str
    is_verified: bool = False


class TraceEntry(BaseModel):
    """One step of the reasoning that led to a decision."""

    agent: str
    kind: TraceKind
    text: str
    evidence_ids: list[str] = Field(default_factory=list)


class ProposedChange(BaseModel):
    """Suggested edit to the protocol text."""

    path: str
    before: str
    after: str


class Decision(BaseModel):
    """A finding the clinical team reviews (a Decision Card)."""

    decision_id: str
    step_id: StepId
    severity: Severity
    title: str
    claim: str
    evidence: list[Evidence] = Field(default_factory=list)
    trace: list[TraceEntry] = Field(default_factory=list)
    proposed_change: ProposedChange | None = None
    # Decisions from earlier steps this one builds on (traceability).
    derived_from: list[str] = Field(default_factory=list)


class Metric(BaseModel):
    """Labelled figure shown on a step."""

    label: str
    value: str
    tone: MetricTone = MetricTone.NEUTRAL


class StepData(BaseModel):
    """Everything one /demo section shows: summary, metrics, decisions."""

    id: StepId
    title: str
    summary: str
    headline: Metric
    metrics: list[Metric] = Field(default_factory=list)
    decisions: list[Decision] = Field(default_factory=list)


class UploadFileResponse(BaseModel):
    """Result of uploading a protocol PDF; protocol_id keys later calls."""

    protocol_id: str
    title: str
    page_count: int
    step: StepData


class StepRecommendationRequest(BaseModel):
    """Body of every recommendation endpoint."""

    protocol_id: str = Field(min_length=1)
