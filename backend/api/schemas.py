"""Pydantic schemas and enums for the backend HTTP API."""

from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, Field

from backend.shared.messages import (
    ProposedFix,
    RuleFamily,
    RuleFinding,
    RunResult,
    SponsorInput,
)


class ProtocolStatus(StrEnum):
    """Lifecycle status of a clinical protocol."""

    UPLOADED = "uploaded"
    ANALYZING = "analyzing"
    READY = "ready"


class PipelineStep(StrEnum):
    """Pipeline analysis step producing recommendations."""

    COMPLETENESS = "completeness"
    COMPARISON = "comparison"
    COHORT = "cohort"


class Severity(StrEnum):
    """Severity level of an identified protocol gap."""

    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"


class RecommendationStatus(StrEnum):
    """Review decision status for a recommendation."""

    PENDING = "pending"
    ACCEPTED = "accepted"
    REJECTED = "rejected"


class HealthResponse(BaseModel):
    """Response returned by the health check endpoint."""

    status: Literal["ok"] = "ok"


class ProtocolCreateRequest(BaseModel):
    """Payload to create a new protocol for gap analysis."""

    title: str = Field(min_length=1)
    data: dict[str, object] = Field(default_factory=dict)


class ProtocolSummary(BaseModel):
    """Summary representation of a registered protocol."""

    protocol_id: str
    title: str
    status: ProtocolStatus
    data: dict[str, object] = Field(default_factory=dict)


class Recommendation(BaseModel):
    """Gap recommendation generated by an agent pipeline step."""

    recommendation_id: str
    protocol_id: str
    source_step: PipelineStep
    severity: Severity
    title: str
    description: str
    status: RecommendationStatus = RecommendationStatus.PENDING
    comment: str | None = None
    details: dict[str, object] = Field(default_factory=dict)


class RecommendationDecisionRequest(BaseModel):
    """Reviewer decision payload for a recommendation."""

    status: RecommendationStatus
    comment: str | None = None


class RunInfo(BaseModel):
    """Rule and comparator counts for a compliance evaluation run."""

    rules_evaluated: int
    comparators_used: int = 0


class StatusCounts(BaseModel):
    """Aggregated rule finding counts across all five evaluation statuses."""

    fired: int
    passed: int
    not_applicable: int
    insufficient_comparators: int
    cannot_assess: int
    total: int


class FamilySummary(BaseModel):
    """Per-family summary of fired and applicable rules for UI charts."""

    family: RuleFamily
    label: str
    fired: int
    applicable: int


class FindingView(RuleFinding):
    """Frontend representation of a rule finding with its composite ID."""

    finding_id: str


class ComplianceReportResponse(BaseModel):
    """HTTP response payload for a protocol compliance report."""

    protocol_id: str
    protocol_title: str
    protocol_version: str | None = None
    run: RunInfo
    before: RunResult
    after: RunResult | None = None
    counts: StatusCounts
    families: list[FamilySummary]
    top_finding_ids: list[str]
    findings: list[FindingView]
    fixes: list[ProposedFix] = Field(default_factory=list)
    new_findings_after_fixes: list[FindingView] = Field(default_factory=list)
    sponsor_inputs_needed: list[SponsorInput] = Field(default_factory=list)
